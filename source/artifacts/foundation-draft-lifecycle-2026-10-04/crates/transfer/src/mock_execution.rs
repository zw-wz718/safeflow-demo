//! Isolated, single-process simulated settlement bank. NOT a Runtime funds tool.
//!
//! Identity arguments must be server-resolved. This adapter is not an authorization
//! boundary: a future funds adapter must obtain and atomically consume a real
//! execution permit through the foundation before calling a bank. Do not expose
//! this demo directly to an LLM, HTTP client, or customer UI.


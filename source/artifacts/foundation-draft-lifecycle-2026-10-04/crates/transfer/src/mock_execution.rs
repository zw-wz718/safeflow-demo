/// Book balance and outstanding holds are separate from completed ledger entries.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct MockAccountFunds {
    pub booked: DecimalAmount,
    pub reserved: DecimalAmount,
    pub available: DecimalAmount,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MockTransferError {
    InvalidRequest,
    IdempotencyConflict,
    OperationConflict,
    ResourceNotAccessible,
    OperationNotFound,
    NotPending,
    OutgoingStateUnknown,
    Unavailable,
}
impl MockTransferError {
    pub fn reason_code(self) -> &'static str {
        match self {
            Self::InvalidRequest => "INVALID_REQUEST",
            Self::IdempotencyConflict => "IDEMPOTENCY_CONFLICT",
            Self::OperationConflict => "OPERATION_CONFLICT",
            Self::ResourceNotAccessible => "RESOURCE_NOT_ACCESSIBLE",
            Self::OperationNotFound => "OPERATION_NOT_FOUND",
            Self::NotPending => "NOT_PENDING",
            Self::OutgoingStateUnknown => "OUTGOING_STATE_UNKNOWN",
            Self::Unavailable => "MOCK_BANK_UNAVAILABLE",
        }
    }
}
impl std::fmt::Display for MockTransferError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.reason_code())
    }
}
impl std::error::Error for MockTransferError {}

struct Account {
    owner: UserId,
    cents: u64,
    outgoing: MockOutgoingState,
}

/// Simulated ACCOUNT outgoing decision. This is not the card_locks source of truth.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MockOutgoingState {
    Allowed,
    Blocked,
    Unknown,
}
struct Operation {
    request: MockTransferRequest,
    key: IdempotencyKey,
    receipt: MockTransferReceipt,
    submission_receipt: MockTransferReceipt,
}
struct State {
    accounts: HashMap<ResourceId, Account>,
    operations: HashMap<(UserId, OperationId), Operation>,
    keys: HashMap<(UserId, IdempotencyKey), OperationId>,
    ledger: Vec<MockTransferTransaction>,
    query_available: bool,
}

/// Trusted demonstration setup only; never accepted as a transfer input field.
#[derive(Clone, Copy, Debug)]
pub enum MockBehavior {
    Immediate,
    Decline,
    Pending,
    LostReplyAfterCommit,
}

/// Fixture control representing the bank's authoritative later outcome.
/// NOT an operation that can be performed by a customer or an LLM.
#[derive(Clone, Copy, Debug)]
pub enum MockResolution {
    Succeed,
    Fail,
}

#[derive(Clone)]
pub struct MockTransferBank {
    state: Arc<Mutex<State>>,
    clock: Arc<dyn Clock + Send + Sync>,
    behavior: MockBehavior,
}

impl MockTransferBank {
    /// Virtual identities and routing, deliberately separate from the immutable
    /// read-only MockBankGateway fixture. Never route a recipient by masked tails.
    pub fn demo(clock: Arc<dyn Clock + Send + Sync>) -> Self {
        Self::demo_with_behavior(clock, MockBehavior::Immediate)
    }

    pub fn demo_with_behavior(clock: Arc<dyn Clock + Send + Sync>, behavior: MockBehavior) -> Self {
        let accounts = [
            (
                ResourceId::parse("account_001").expect("fixture"),
                Account {
                    owner: UserId::parse("user_demo").expect("fixture"),
                    cents: 128_800,
                    outgoing: MockOutgoingState::Allowed,
                },
            ),
            (
                ResourceId::parse("account_002").expect("fixture"),
                Account {
                    owner: UserId::parse("user_recipient").expect("fixture"),
                    cents: 0,
                    outgoing: MockOutgoingState::Allowed,
                },
            ),
        ]
        .into_iter()
        .collect();
        Self {
            state: Arc::new(Mutex::new(State {
                accounts,
                operations: HashMap::new(),
                keys: HashMap::new(),
                ledger: vec![],
                query_available: true,
            })),
            clock,
            behavior,
        }
    }

    /// Low-level MOCK bank operation, not user confirmation or permission issuance.
    pub fn submit(
        &self,
        user: &UserId,
        key: &IdempotencyKey,
        request: MockTransferRequest,
    ) -> Result<MockTransferReceipt, MockTransferError> {
        validate_request(user, key, &request)?;
        let cents = amount_cents(&request.amount)?;
        if cents == 0 || request.draft_version == 0 {
            return Err(MockTransferError::InvalidRequest);
        }
        let mut state = self
            .state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?;
        if let Some(existing_id) = state.keys.get(&(user.clone(), key.clone())) {
            let existing = state
                .operations
                .get(&(user.clone(), existing_id.clone()))
                .expect("atomic index");
            return if existing.request == request {
                Ok(existing.submission_receipt.clone())
            } else {
                Err(MockTransferError::IdempotencyConflict)
            };
        }
        if let Some(existing) = state
            .operations
            .get(&(user.clone(), request.operation_id.clone()))
        {
            debug_assert!(existing.key != *key);
            return Err(MockTransferError::OperationConflict);
        }
        let completed_at = timestamp(self.clock.now())?;
        let outgoing = state
            .accounts
            .get(&request.payer_account_id)
            .filter(|a| a.owner == *user)
            .ok_or(MockTransferError::ResourceNotAccessible)?
            .outgoing;
        if user.as_str() != "user_demo" || request.payee_id.as_str() != "payee_008" {
            return Err(MockTransferError::ResourceNotAccessible);
        }
        if outgoing == MockOutgoingState::Unknown {
            return Err(MockTransferError::OutgoingStateUnknown);
        }
        let mut receipt = MockTransferReceipt {
            proposal_version: 1,
            task_id: request.task_id.clone(),
            operation_id: request.operation_id.clone(),
            draft_id: request.draft_id.clone(),
            draft_version: request.draft_version,
            payer_account_id: request.payer_account_id.clone(),
            payee_id: request.payee_id.clone(),
            amount: request.amount.clone(),
            currency: request.currency,
            status: ToolResultStatus::Processing,
            reason_code: None,
            completed_at: None,
        };
        if outgoing == MockOutgoingState::Blocked {
            fail(&mut receipt, "ACCOUNT_OUTGOING_BLOCKED");
        } else {
            match self.behavior {
                MockBehavior::Decline => fail(&mut receipt, "BANK_DECLINED"),
                MockBehavior::Immediate | MockBehavior::LostReplyAfterCommit => {
                    settle(&mut state, &request, cents, &mut receipt, &completed_at)?
                }
                MockBehavior::Pending => {
                    if available_cents(&state, &request.payer_account_id, None)? < cents {
                        fail(&mut receipt, "INSUFFICIENT_FUNDS");
                    } else {
                        receipt.reason_code = Some("AWAITING_BANK_RESULT".into());
                    }
                }
            }
        }
        let mut submission_receipt = receipt.clone();
        if matches!(self.behavior, MockBehavior::LostReplyAfterCommit)
            && receipt.status == ToolResultStatus::Succeeded
        {
            submission_receipt.status = ToolResultStatus::Processing;
            submission_receipt.reason_code = Some("OUTCOME_UNKNOWN".into());
            submission_receipt.completed_at = None;
        }
        state
            .keys
            .insert((user.clone(), key.clone()), request.operation_id.clone());
        state.operations.insert(
            (user.clone(), request.operation_id.clone()),
            Operation {
                request,
                key: key.clone(),
                receipt,
                submission_receipt: submission_receipt.clone(),
            },
        );
        Ok(submission_receipt)
    }

    pub fn query(
        &self,
        user: &UserId,
        operation_id: &OperationId,
    ) -> Result<MockTransferReceipt, MockTransferError> {
        let state = self
            .state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?;
        if !state.query_available {
            return Err(MockTransferError::Unavailable);
        }
        state
            .operations
            .get(&(user.clone(), operation_id.clone()))
            .map(|o| o.receipt.clone())
            .ok_or(MockTransferError::OperationNotFound)
    }

    /// Test/demo driver only: a real adapter receives this fact from its bank,
    /// not from a user command or a locally elapsed waiting timer.
    pub fn resolve_mock(
        &self,
        user: &UserId,
        operation_id: &OperationId,
        outcome: MockResolution,
    ) -> Result<MockTransferReceipt, MockTransferError> {
        let mut state = self
            .state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?;
        let scope = (user.clone(), operation_id.clone());
        let operation = state
            .operations
            .get(&scope)
            .ok_or(MockTransferError::OperationNotFound)?;
        if operation.receipt.status != ToolResultStatus::Processing {
            return Err(MockTransferError::NotPending);
        }
        let request = operation.request.clone();
        let mut receipt = operation.receipt.clone();
        match outcome {
            MockResolution::Fail => fail(&mut receipt, "BANK_DECLINED"),
            MockResolution::Succeed => {
                let completed_at = timestamp(self.clock.now())?;
                settle(
                    &mut state,
                    &request,
                    amount_cents(&request.amount)?,
                    &mut receipt,
                    &completed_at,
                )?;
            }
        }
        state.operations.get_mut(&scope).expect("checked").receipt = receipt.clone();
        Ok(receipt)
    }

    /// Trusted fixture control, deliberately absent from the request schema.
    pub fn set_query_available_mock(&self, available: bool) -> Result<(), MockTransferError> {
        self.state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?
            .query_available = available;
        Ok(())
    }

    /// Fixture only. Actual lock lookup belongs to the card/account owner and
    /// must be rechecked by the future foundation funds assembly.
    pub fn set_outgoing_state_mock(
        &self,
        user: &UserId,
        account_id: &ResourceId,
        outgoing: MockOutgoingState,
    ) -> Result<(), MockTransferError> {
        let mut state = self
            .state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?;
        state
            .accounts
            .get_mut(account_id)
            .filter(|a| a.owner == *user)
            .ok_or(MockTransferError::ResourceNotAccessible)?
            .outgoing = outgoing;
        Ok(())
    }

    pub fn balance(
        &self,
        user: &UserId,
        account_id: &ResourceId,
    ) -> Result<DecimalAmount, MockTransferError> {
        Ok(self.funds(user, account_id)?.available)
    }

    pub fn funds(
        &self,
        user: &UserId,
        account_id: &ResourceId,
    ) -> Result<MockAccountFunds, MockTransferError> {
        let state = self
            .state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?;
        let account = state
            .accounts
            .get(account_id)
            .filter(|a| a.owner == *user)
            .ok_or(MockTransferError::ResourceNotAccessible)?;
        let available = available_cents(&state, account_id, None)?;
        Ok(MockAccountFunds {
            booked: decimal(account.cents),
            reserved: decimal(account.cents - available),
            available: decimal(available),
        })
    }

    pub fn transactions(
        &self,
        user: &UserId,
    ) -> Result<Vec<MockTransferTransaction>, MockTransferError> {
        let state = self
            .state
            .lock()
            .map_err(|_| MockTransferError::Unavailable)?;
        Ok(state
            .ledger
            .iter()
            .filter(|t| {
                state
                    .accounts
                    .get(&t.account_id)
                    .is_some_and(|a| a.owner == *user)
            })
            .cloned()
            .collect())
    }
}

/// Caller holds the single bank lock. Both balances and both entries are committed
/// with the operation record; no I/O or fallible business check follows mutation.
fn settle(
    state: &mut State,
    request: &MockTransferRequest,
    cents: u64,
    receipt: &mut MockTransferReceipt,
    completed_at: &str,
) -> Result<(), MockTransferError> {
    let receiver_id = ResourceId::parse("account_002").expect("fixture routing");
    match state.accounts[&request.payer_account_id].outgoing {
        MockOutgoingState::Unknown => return Err(MockTransferError::OutgoingStateUnknown),
        MockOutgoingState::Blocked => {
            fail(receipt, "ACCOUNT_OUTGOING_BLOCKED");
            return Ok(());
        }
        MockOutgoingState::Allowed => {}
    }
    if available_cents(
        state,
        &request.payer_account_id,
        Some(&request.operation_id),
    )? < cents
    {
        fail(receipt, "INSUFFICIENT_FUNDS");
        return Ok(());
    }
    let Some(remaining) = state.accounts[&request.payer_account_id]
        .cents
        .checked_sub(cents)
    else {
        fail(receipt, "INSUFFICIENT_FUNDS");
        return Ok(());
    };
    let Some(credited) = state.accounts[&receiver_id].cents.checked_add(cents) else {
        fail(receipt, "RECEIVER_BALANCE_OVERFLOW");
        return Ok(());
    };
    state
        .accounts
        .get_mut(&request.payer_account_id)
        .expect("checked")
        .cents = remaining;
    state.accounts.get_mut(&receiver_id).expect("fixture").cents = credited;
    for (account_id, direction, suffix) in [
        (
            request.payer_account_id.clone(),
            TransferDirection::Debit,
            "debit",
        ),
        (receiver_id, TransferDirection::Credit, "credit"),
    ] {
        state.ledger.push(MockTransferTransaction {
            transaction_id: format!("{}:{suffix}", request.operation_id),
            operation_id: request.operation_id.clone(),
            account_id,
            card_id: None,
            merchant_id: None,
            transaction_type: "TRANSFER".into(),
            direction,
            amount: request.amount.clone(),
            currency: request.currency,
            status: "COMPLETED".into(),
            completed_at: completed_at.into(),
        });
    }
    receipt.status = ToolResultStatus::Succeeded;
    receipt.reason_code = None;
    receipt.completed_at = Some(completed_at.into());
    Ok(())
}

fn available_cents(
    state: &State,
    account_id: &ResourceId,
    settling: Option<&OperationId>,
) -> Result<u64, MockTransferError> {
    let reserved = state
        .operations
        .values()
        .filter(|operation| {
            operation.request.payer_account_id == *account_id
                && operation.receipt.status == ToolResultStatus::Processing
                && Some(&operation.request.operation_id) != settling
        })
        .try_fold(0u64, |total, operation| {
            total
                .checked_add(amount_cents(&operation.request.amount)?)
                .ok_or(MockTransferError::InvalidRequest)
        })?;
    state
        .accounts
        .get(account_id)
        .ok_or(MockTransferError::ResourceNotAccessible)?
        .cents
        .checked_sub(reserved)
        .ok_or(MockTransferError::Unavailable)
}
fn fail(receipt: &mut MockTransferReceipt, reason: &str) {
    receipt.status = ToolResultStatus::Failed;
    receipt.reason_code = Some(reason.into());
    receipt.completed_at = None;
}

pub(crate) fn validate_request(
    user: &UserId,
    key: &IdempotencyKey,
    request: &MockTransferRequest,
) -> Result<(), MockTransferError> {
    for value in [
        user.as_str(),
        key.as_str(),
        request.task_id.as_str(),
        request.operation_id.as_str(),
        request.draft_id.as_str(),
        request.payer_account_id.as_str(),
        request.payee_id.as_str(),
    ] {
        if value.len() > 128
            || value.is_empty()
            || value.chars().any(|c| c.is_whitespace() || c.is_control())
        {
            return Err(MockTransferError::InvalidRequest);
        }
    }
    if request.remark.chars().count() > 140 || request.remark.chars().any(char::is_control) {
        return Err(MockTransferError::InvalidRequest);
    }
    Ok(())
}

pub(crate) fn amount_cents(amount: &DecimalAmount) -> Result<u64, MockTransferError> {
    let (whole, fraction) = amount
        .as_str()
        .split_once('.')
        .ok_or(MockTransferError::InvalidRequest)?;
    whole
        .parse::<u64>()
        .ok()
        .and_then(|v| v.checked_mul(100))
        .and_then(|v| v.checked_add(fraction.parse().ok()?))
        .ok_or(MockTransferError::InvalidRequest)
}
fn decimal(cents: u64) -> DecimalAmount {
    DecimalAmount::parse(format!("{}.{:02}", cents / 100, cents % 100)).expect("integer decimal")
}
fn timestamp(seconds: u64) -> Result<String, MockTransferError> {
    i64::try_from(seconds)
        .ok()
        .and_then(|s| DateTime::<Utc>::from_timestamp(s, 0))
        .map(|t| t.to_rfc3339_opts(chrono::SecondsFormat::Secs, true))
        .ok_or(MockTransferError::InvalidRequest)
}

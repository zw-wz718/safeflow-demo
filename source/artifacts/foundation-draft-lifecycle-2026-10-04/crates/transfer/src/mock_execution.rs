/// Transfer-owner proposal v1, not a frozen cross-team contract.
/// IDs/version must be copied from a trusted current draft, not generated by an LLM.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MockTransferRequest {
    pub task_id: TaskId,
    /// Stable BUSINESS operation ID; not a Runtime tool-node operation ID.
    pub operation_id: OperationId,
    pub draft_id: ResourceId,
    pub draft_version: u32,
    pub payer_account_id: ResourceId,
    pub payee_id: ResourceId,
    pub amount: DecimalAmount,
    pub currency: CnyCurrency,
    /// REMARK-140-v1: at most 140 Unicode scalar values, no control characters.
    /// Empty is allowed; accepted text is bound unchanged to the idempotency key.
    pub remark: String,
}

impl MockTransferRequest {
    /// Trusted-backend parameter projection ONLY, never confirmation or a permit.
    /// The caller must read/lock the actual current draft in the public funds
    /// transaction. This checks a supplied snapshot, not database freshness.
    pub fn from_trusted_draft(
        context: &safeflow_contracts::ExecutionContext,
        draft: &crate::StoredDraft,
        expected_version: u32,
        server_now: u64,
    ) -> Result<Self, crate::IntegrationError> {
        use crate::{DraftError, DraftStatus, IntegrationError};
        if draft.user_id != context.authenticated_user_id {
            return Err(DraftError::AccessDenied.into());
        }
        if draft.task_id != context.task_id {
            return Err(IntegrationError::TaskMismatch);
        }
        if draft.plan_version != expected_version {
            return Err(DraftError::VersionConflict {
                expected: expected_version.into(),
                actual: draft.plan_version.into(),
            }
            .into());
        }
        match draft.status {
            DraftStatus::Cancelled => return Err(DraftError::Cancelled.into()),
            DraftStatus::Expired => return Err(DraftError::Expired.into()),
            DraftStatus::NeedsInformation => return Err(DraftError::NotReady.into()),
            DraftStatus::ReadyToConfirm => {}
        }
        if server_now >= draft.expires_at {
            return Err(DraftError::Expired.into());
        }
        let details = draft.details.as_ref().ok_or(DraftError::NotReady)?;
        let request = Self {
            task_id: draft.task_id.clone(),
            operation_id: draft.operation_id.clone(),
            draft_id: draft.draft_id.clone(),
            draft_version: draft.plan_version,
            payer_account_id: details.account.account_id.clone(),
            payee_id: details.payee.payee_id.clone(),
            amount: details.amount.clone(),
            currency: details.currency,
            remark: details.remark.clone(),
        };
        let validation_key =
            IdempotencyKey::parse("projection-validation-only").expect("static identifier");
        validate_request(&context.authenticated_user_id, &validation_key, &request)
            .map_err(|_| IntegrationError::MappingError)?;
        if request.draft_version == 0
            || amount_cents(&request.amount).map_err(|_| IntegrationError::MappingError)? == 0
        {
            return Err(DraftError::NotReady.into());
        }
        Ok(request)
    }
}

/// Existing read-only contract, backed by the SAME mock ledger balances.
impl BankGateway for MockTransferBank {
    fn get_account_balance<'a>(
        &'a self,
        user: &'a UserId,
        account_id: &'a ResourceId,
    ) -> ContractFuture<'a, Result<GetAccountBalanceOutput, BankError>> {
        Box::pin(async move {
            GetAccountBalanceInput {
                account_id: account_id.clone(),
            }
            .validate()?;
            let available_balance = self.balance(user, account_id).map_err(bank_read_error)?;
            Ok(GetAccountBalanceOutput {
                account: MaskedAccountView {
                    account_id: account_id.clone(),
                    display_name: "模拟账户".into(),
                    masked_account_no: if account_id.as_str() == "account_001" {
                        "**** 0001"
                    } else {
                        "**** 1024"
                    }
                    .into(),
                    currency: CnyCurrency::Cny,
                },
                available_balance,
                as_of: timestamp(self.clock.now()).map_err(bank_read_error)?,
            })
        })
    }

    fn find_payees<'a>(
        &'a self,
        user: &'a UserId,
        query: &'a str,
    ) -> ContractFuture<'a, Result<FindPayeesOutput, BankError>> {
        Box::pin(async move {
            FindPayeesInput {
                query: query.into(),
            }
            .validate()?;
            let state = self.state.lock().map_err(|_| BankError::Unavailable)?;
            if !state.accounts.values().any(|a| a.owner == *user) {
                return Err(BankError::ResourceNotOwned);
            }
            let candidates = if user.as_str() == "user_demo"
                && ("小李".contains(query) || query == "payee_008")
            {
                vec![PayeeView {
                    payee_id: ResourceId::parse("payee_008").expect("fixture"),
                    display_name: "小李".into(),
                    bank_name: "模拟银行".into(),
                    masked_account_no: "**** 1024".into(),
                }]
            } else {
                vec![]
            };
            Ok(FindPayeesOutput { candidates })
        })
    }
}

fn bank_read_error(error: MockTransferError) -> BankError {
    match error {
        MockTransferError::ResourceNotAccessible | MockTransferError::OperationNotFound => {
            BankError::ResourceNotOwned
        }
        MockTransferError::Unavailable => BankError::Unavailable,
        _ => BankError::InvalidResponse,
    }
}

